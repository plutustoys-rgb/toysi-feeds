"""forbidden_products.py — ЄДИНЕ місце, де записано, що ми НЕ продаємо (політика магазину, не маржа і не стан складу).

ЧОМУ ОКРЕМИЙ МОДУЛЬ, а не фільтр у `parser.fetch_toysi_catalog()`: каталог читають і не-фідові споживачі
(order_router, daily_report, repricer, competitor_pricing, promo_margin_guard, service_watchdog…). Прибрати товар із каталогу
= `order_router` вважатиме його «немає в наявності» (order_router.py:190-206) і ВІДКРИТЕ замовлення на нього зависне. Тому
заборона застосовується лише в ГЕНЕРАТОРАХ вітрини (де вирішується, що показувати покупцеві), а замовлення, що вже є, йдуть як і йшли.

КЛЮЧ — назва категорії Toysi (нижній регістр, як у `generate_prom_feed_top.is_excluded_category`), а НЕ категорія Prom: Prom сам
переставляє категорії ≈2 420 разів на місяць, категорія Toysi стабільна.

ЩО ТУТ І ЧОМУ (рішення власника 2026-10-07, дослівно «приберіть»; Консультант, дитячий магазин — репутація, не маржа):
  «мечі, ножі та шаблі» — 246 позицій Toysi: ножі, мечі, сокири, щити, сувенірні бокси. За товаром категорія однорідна; «змішаність»
  лише в таксономії Prom (частину Prom кладе в «Игрушечные пистолеты, арбалеты и сабли» = іграшка). 5 іграшкових шабель зі вітрини
  Prom вилітають разом — свідомо прийнято (0,4% вітрини), бо ключ Toysi-категорії стійкий, а Prom-категорії — ні.

ДОДАТИ ЩОСЬ: один рядок у FORBIDDEN_TOYSI_CATEGORIES (ціла категорія) або FORBIDDEN_PRODUCT_IDS (точковий pid) + `python test_forbidden_products.py --live` (перевіряє на живому каталозі, що жоден фід не містить
заборонений SKU). НОВИЙ ГЕНЕРАТОР вітрини ЗОБОВ'ЯЗАНИЙ викликати `is_forbidden(item)` у місці відбору — `test_forbidden_products.py` падає, якщо
файл generate_*_feed.py / site/build_site.py не імпортує цей модуль (запобіжник проти «принцип зроблено в одному шарі, сусідній забули»).
"""

FORBIDDEN_TOYSI_CATEGORIES = frozenset({
    "мечі, ножі та шаблі",
})

# ТОЧКОВІ pid поза забороненою категорією (рішення Консультанта 2026-10-07 після перегляду всіх 62 кандидатів за словом; правило за словом
# НЕ береться: precision ≈ 8%, хибні спрацьовування знімали б товар із шести каналів). Той самий прийом, що `EVA_MANUAL_EXCLUDE_IDS`
# (generate_eva_feed.py: «точковий ID — БЕЗ побічних жертв»). Нових кандидатів за словом доповідає `forbidden_watch.py` (алерт, не автозаборона).
FORBIDDEN_PRODUCT_IDS = {
    "181821": "Сувенірна сокира «Череп» (Дерев'яні іграшки)",
    "166976": "Ніж сувенірний «Викидуха Скелетон» (Уцінка)",
    "180570": "Ніж сувенірний «Викидуха Стріла» (Уцінка)",
    "293570": "Сувенірний меч «Катана міні» 47,5 см (Уцінка)",
    "275143": "Сувенірний ніж «KUNAI» (Уцінка)",
    "306414": "Ніж із тюбиком крові (прикол, Маскарадні костюми) — імітація удару ножем із кров'ю; решта маскараду лишається",
}


def is_forbidden(item) -> bool:
    """True, якщо позиція належить до забороненої на вітрині Toysi-категорії АБО її pid у FORBIDDEN_PRODUCT_IDS. Приймає dict товару."""
    if not isinstance(item, dict):
        return False
    if str(item.get("id") or "") in FORBIDDEN_PRODUCT_IDS:
        return True
    return (item.get("category_name") or "").strip().lower() in FORBIDDEN_TOYSI_CATEGORIES
