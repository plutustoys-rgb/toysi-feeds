    for ceiling, rate in ROZETKA_CATEGORY_COMMISSION["дитячі іграшки"]:
        if price <= ceiling:
            return rate
    return ROZETKA_CATEGORY_COMMISSION["дитячі іграшки"][-1][1]  # недосяжно (остання межа = inf), про всяк випадок


