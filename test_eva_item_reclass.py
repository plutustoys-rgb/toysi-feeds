"""test_eva_item_reclass.py — етап 1б EVA (20.10.2026, замір Аудитора після етапу 1): (1) покомпонентна перекласифікація не-пазлів із категорій «Пазли» (вкладиші/Сегена/рамки → Toysi 99122; «Мозаїка …» → 99141; «пазли-вкладиші» лишаються пазлами);
(2) «російська мова в назві» (модерація EVA відхиляє: «44 Котенка», «Цвет, счет…») не йде у фід, а українське «з набором» — йде; (3) карта: 99122 «Дерев'яні вкладиші» → «Іграшки для малюків» (як зіставив кабінет), а не «Пазли»;
(4) _item_category не чіпає товари інших категорій і не падає на порожніх полях."""
import os
import sys
from pathlib import Path

if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
os.environ["AUDIT_NO_TELEGRAM"] = "1"
sys.path.insert(0, str(Path(__file__).parent))
import generate_eva_feed as g  # noqa: E402

F = []


def chk(n, c):
    print(f"[{'OK ' if c else 'FAIL'}] {n}")
    if not c:
        F.append(n)


def it(name, cid="99031", cname="Пазли і вкладиші"):
    return {"id": "1", "name": name, "category_id": cid, "category_name": cname}


chk("карта: 99122 → «Іграшки для малюків» (120713), не «Пазли»", g.EVA_CATEGORY_MAP["99122"]["id"] == "120713" and g.EVA_CATEGORY_MAP["99031"]["id"] == "105311")
chk("вкладиші / Сегена / рамка-вкладиш у «Пазли і вкладиші» → 99122", all(g._item_category(it(n))[0] == "99122" for n in ('Вкладиші "Мама, тато і малюк"', 'Дощечки Сегена "Овочі"', "Дерев'яна рамка-вкладиш (Вид 4)")))
chk("«Мозаїка …» (і з категорії 99086) → 99141 «Мозаїки»", g._item_category(it('Мозаїка "Слоненя"'))[0] == "99141" and g._item_category(it('Мозаїка "Ведмідь"', "99086", "Пазли для малюків"))[0] == "99141")
chk("«пазли-вкладиші» і звичайні пазли ЛИШАЮТЬСЯ в своїй категорії", g._item_category(it('Дерев\'яні пазли-вкладиші "Морська зірка"')) == ("99031", "Пазли і вкладиші") and g._item_category(it('Пазли "Трактор", 100 ел', "99218", "Пазли Trefl")) == ("99218", "Пазли Trefl"))
chk("товар НЕ з пазлів (конструктор із «рамкою») не чіпається", g._item_category(it("Конструктор з рамкою", "99058", "Конструктори")) == ("99058", "Конструктори"))
chk("порожні поля не валять", g._item_category({}) == ("", "") and g._item_category({"name": None, "category_id": None}) == ("", ""))
chk("перенесені товари отримують ЛЕГАСІ-id кабінету (99122 / 99141), а не незіставлений EVA-id", g._map_eva_category(*g._item_category(it('Вкладиші "X"')))[0] == "99122" and g._map_eva_category(*g._item_category(it('Мозаїка "X"')))[0] == "99141")
chk("власні «пазл»-товари 99122 лишаються пазлами (99031), решта 99122 — на місці", g._item_category(it('Пазл-вкладиш "Динозаври"', "99122", "Дерев'яні вкладиші"))[0] == "99031" and g._item_category(it('Контурний пазл "Пінгвін"', "99122", "Дерев'яні вкладиші"))[0] == "99031" and g._item_category(it('Піраміда "X"', "99122", "Дерев'яні вкладиші"))[0] == "99122")
chk("сортери з пазлових категорій → 99122", g._item_category(it('Сортер "Більше-менше"'))[0] == "99122")
g.EVA_ITEM_RECLASS_ON = False
chk("перемикач item_reclass=false: перекласифікація вимкнена (категорія як у Toysi)", g._item_category(it('Вкладиші "X"')) == ("99031", "Пазли і вкладиші") and g._item_category(it('Пазл "X"', "99122", "Дерев'яні вкладиші"))[0] == "99122")
g.EVA_ITEM_RECLASS_ON = True
chk("російські назви з модерації EVA — виключаються", all(g._name_has_forbidden_word(n) for n in ('Пазли "44 Котенка", 35 ел', 'Пазл "Цвет, счет и направления: Тракторы"', 'Ведро пластиковое "Вспыш" (1 л)', 'Эко-сумка Украина', 'Рамка-вкладиш "Лягушенок"', "Пазл 'Цвет'")))
chk("українське «з пісочним набором» / «набір» НЕ вважається російським", not any(g._name_has_forbidden_word(n) for n in ('Відро "Квіточка" з машинкою і пісочним набором (жовте)', 'Набір для творчості "Кошеня"', "Пазли «Котики», 60 ел")))
print("\nFAIL:" if F else "\nOK: усі перевірки пройдені", *F, sep="\n")
sys.exit(1 if F else 0)
