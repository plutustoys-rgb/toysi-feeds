def compute_floor(cost: float, total_commission: float, target_margin: float) -> float:
    """Нижня межа ціни для заданої цільової маржі (частка cost, напр.
    MIN_PROFIT чи MIN_PROFIT_COMPETITOR_FLOOR) при заданій сумарній
    комісії. Спільна формула для обох "шляхів" decide_price_for_platform()
    і для check_price_floor() (prom_catalog_auditor.py) — той самий
    рефакторинг, що й compute_total_commission() вище.

    ВИДАЛЕНО абсолютний floor у гривнях (2026-07-23, пряме рішення
    власниці — знахідка "cheap-sku-floor-margin-conflict", див. коментар
    над колишніми MIN_PROFIT_UAH/FIXED_COST_UAH вище): target_margin сам
    по собі Є мінімальним прибутком (власниця: "мінімальна маржа 3% —
    це наш мінімальний профіт на будь-якому товарі"), без додаткового
    твердого гривневого шару поверх, що на дешевих SKU домінував над
    3%-конкурентним floor і блокував конкурентність 335/970 (35%) SKU."""
    return (cost + cost * target_margin) / (1 - total_commission)


def canonical_competitor_floor(
    cost: float,
    candidate: float,
    total_commission: float,
    target_margin: float = MIN_PROFIT_COMPETITOR_FLOOR,
) -> float:
    """Канонічна нижня межа Prom при ВІДОМОМУ конкуренті (формула власниці,
    2026-07-26 — "запишіть формулу раз і назавжди", SKU 292858):
        B = cost*(1+target_margin) + candidate*сумарна_комісія
    ПРЯМЕ ДОДАВАННЯ від конкретного candidate (=competitor - PRICE_STEP), а НЕ
    ділення `cost*(1+m)/(1-commission)` (compute_floor) — власниця явно відкинула
    ділення, бо воно завищує floor від ще-нерозрахованої ціни. Спільна точка для
    decide_price_for_platform() (Шлях 2 Prom) і floor-гарда в generate_prom_feed
    — щоб гард не перебивав коректний undercut завищеним division-floor (баг
    2026-08-22: 325 SKU піднімались НАД ринок при свіжому зростанні собівартості).
    Rozetka має власний сходинковий floor (_resolve_rozetka_floor) — цю не чіпає."""
    return round(cost * (1 + target_margin) + candidate * total_commission, 2)


def _resolve_rozetka_floor(cost: float, target_margin: float, payment_commission: float) -> tuple[float, float]:
    """Rozetka-специфічне: розв'язує коло "ціна залежить від комісії,
    комісія (сходинка) залежить від ціни" ітеративно. Починаємо зі
    сходинки за cost (розумна початкова здогадка), рахуємо floor, дивимось,
    у яку сходинку ФАКТИЧНО влазить floor — якщо та сама, готово; якщо ні,
    перераховуємо з новою сходинкою. Збігається за 1-2 ітерації в
    переважній більшості випадків (перевірено на реальних SKU в звіті).

    ПІДТВЕРДЖЕНА ЖИВИМ ТЕСТОМ "мертва зона" біля межі сходинки (напр.
    cost=2500 у "Дитячі іграшки"): floor за нижчою сходинкою (16.2%) падає
    НИЖЧЕ її власної межі (назад у сходинку 23.76%), а floor за вищою
    (23.76%) — ВИЩЕ межі 3999 (у сходинку 16.2%) — справжньої
    самоузгодженої точки не існує, лише вічна осциляція між двома. Захист:
    ROZETKA_TIER_MAX_ITER ітерацій, потім фолбек на НАЙВИЩУ з побачених
    ставок. Це не довільний вибір: НАЙВИЩА ставка дає НАЙВИЩИЙ floor —
    коли ця ціна реально потрапляє на Rozetka, застосується нижча реальна
    ставка (бо ціна впала в дорожчу сходинку), тобто реалізована маржа
    вийде ВИЩОЮ за цільову (безпечний надлишок, не недобір). Протилежний
    вибір (найнижча ставка) дав би ціну, що на практиці впаде в дорожчу
    сходинку і NЕДОБЕРЕ цільову маржу — тому саме "найвища з побачених", а
    не проста осциляція чи середнє."""
    commission = _rozetka_tiered_commission(cost)
    seen_commissions = []
    floor = compute_floor(cost, commission + payment_commission, target_margin)
    for _ in range(ROZETKA_TIER_MAX_ITER):
        seen_commissions.append(commission)
        next_commission = _rozetka_tiered_commission(floor)
        if next_commission == commission:
            return floor, commission
        commission = next_commission
        floor = compute_floor(cost, commission + payment_commission, target_margin)
    commission = max(seen_commissions)
    floor = compute_floor(cost, commission + payment_commission, target_margin)
    return floor, commission


def decide_price_for_platform(
    cost: float,
    min_competitor: float | None,
    platform: str,
    category_name: str | None = None,
    prom_category_id: int | None = None,
) -> dict:
    """
    Рішення про ціну для ОДНОГО майданчика (Prom або Rozetka):
        Шлях 1 (немає конкурента):
            нижня_межа = (cost + cost*MIN_PROFIT) / (1 - комісія_майданчика - комісія_оплати)
            ціна       = max(cost*NO_COMPETITOR_MULT, нижня_межа)
        Шлях 2, Rozetka (є конкурент):
            нижня_межа = (cost + cost*MIN_PROFIT_COMPETITOR_FLOOR) / (1 - комісія_майданчика - комісія_оплати)
            кандидат   = min_competitor - PRICE_STEP (фіксований крок, грн — не %)
            ціна       = max(нижня_межа, кандидат)
        Шлях 2, Prom (є конкурент) — КАНОНІЧНА ФОРМУЛА ВЛАСНИЦІ, 2026-07-26
        ("запишіть формулу раз і на завжди", проговорено й перевірено на
        живому прикладі SKU 292858, конкурент 67₴):
            A (кандидат) = min_competitor - PRICE_STEP
            B (floor)    = cost*(1+MIN_PROFIT_COMPETITOR_FLOOR) + A*сумарна_комісія
        B рахується ПРЯМИМ ДОДАВАННЯМ від A (конкретної відомої ціни), А
        НЕ діленням від ще нерозрахованого floor (це й була помилка старої
        формули, яку власниця виправила напряму) — комісія береться як
        відсоток від candidate, не розв'язується рівнянням "яка ціна дасть
        комісію-як-частку-від-себе-самої".

    Завжди повертає ціну навіть якщо B > A (floor вищий за кандидата) —
    "floor"-категорія нижче лише СИГНАЛІЗУЄ decide_action() (prom_
    competitor_pricer.py), що товар — кандидат на delist (після перевірки
    якості зіставлення конкурента); сама ця функція рішення про
    видалення не приймає, тільки ціну/категорію.

    Rozetka (2026-07-14): комісія — СХОДИНКОВА за ФІНАЛЬНОЮ ціною (не лише
    категорією, як Prom) — floor рахується ітеративно (_resolve_rozetka_floor,
    вирішує коло "ціна <-> сходинка"), формулу власниці 07-26 НЕ зачіпає
    (вона стосувалась явно Prom — "конкурент наипромі"). margin_pct
    рахується ОКРЕМО за вже відомою фінальною ціною (не тим комісія, що
    йшла на floor — Шлях 2 може завершитись на candidate, не на floor, і
    сходинка для нього інша).
    """
    payment_commission = PAYMENT_COMMISSION.get(platform, 0.0)
    target_margin = MIN_PROFIT if min_competitor is None else MIN_PROFIT_COMPETITOR_FLOOR

    if platform == "rozetka":
        floor, floor_commission = _resolve_rozetka_floor(cost, target_margin, payment_commission)
        if floor_commission + payment_commission >= 1:
            raise ValueError(
                f"[{platform}] сумарна комісія {floor_commission + payment_commission:.0%} >= 100% — перевір "
                "ROZETKA_CATEGORY_COMMISSION/PAYMENT_COMMISSION"
            )
    else:
        total_commission = compute_total_commission(platform, category_name, prom_category_id=prom_category_id)
        if total_commission >= 1:
            raise ValueError(
                f"[{platform}] сумарна комісія {total_commission:.0%} >= 100% — перевір "
                "PROM_CATEGORY_COMMISSION/ROZETKA_COMMISSION_DEFAULT/PAYMENT_COMMISSION"
            )
        floor = compute_floor(cost, total_commission, target_margin)

    if min_competitor is None:
        price = round(max(cost * NO_COMPETITOR_MULT, floor), 2)
        result_category = "no_competitor"
    else:
        candidate = round(min_competitor - PRICE_STEP, 2)
        if platform != "rozetka":
            # Канонічна формула власниці (пряме додавання) — винесена у спільний
            # canonical_competitor_floor(), той самий floor кличе floor-гард фіду.
            floor = canonical_competitor_floor(cost, candidate, total_commission, target_margin)
        price = round(max(floor, candidate), 2)
        result_category = "floor" if floor >= candidate else "undercut"

    # Комісія для звітного margin_pct — за ФІНАЛЬНОЮ ціною, окремо від
    # комісії, що йшла на floor (для Rozetka Шлях 2/undercut фінальна ціна
    # може відрізнятись від floor і потрапляти в іншу сходинку).
    final_commission = compute_total_commission(platform, category_name, price, prom_category_id=prom_category_id)

    # ДОДАНО (2026-07-26, пряме прохання власниці — "продаж не повинен бути
    # меншим за собівартість"): абсолютний останній запобіжник, НЕЗАЛЕЖНО
    # від того, яка гілка/формула вище дала ціну. ВАЖЛИВО: перевіряти
    # потрібно ЧИСТУ ВИРУЧКУ (після комісії), а не саму ціну — живо
    # перевірено на edge-case (competitor майже 0₴): ціна виходила ВИЩЕ
    # за cost (37.39 > 36.53), але після віднімання комісії Prom чиста
    # виручка давала margin_pct = -21.9% (реальний збиток). Перша версія
    # цього запобіжника (price < cost) цю ситуацію НЕ ловила. Тепер —
    # мінімальна безпечна ціна рахується так, щоб net_revenue = cost:
    # min_safe_price = cost / (1 - final_commission). Спрацювання цього
    # запобіжника — сигнал, що щось вище порахувалось не так, тож той
    # самий SKU так само позначається "floor" (кандидат на перегляд/
    # delist), а не тихо продається по аварійній ціні. Комісія для
    # Rozetka (сходинкова, залежить від ціни) перераховується ще раз ПІСЛЯ
    # підняття ціни — сходинка могла змінитись.
    if final_commission < 1:
        min_safe_price = round(cost / (1 - final_commission), 2)
        if price < min_safe_price:
            price = min_safe_price
            result_category = "floor"
            final_commission = compute_total_commission(platform, category_name, price, prom_category_id=prom_category_id)

    net_revenue = price * (1 - final_commission)
    margin_pct = round((net_revenue - cost) / cost * 100, 1) if cost else 0.0

    return {
        "platform": platform,
        "floor": round(floor, 2),
        "price": price,
        "category": result_category,
        "margin_pct": margin_pct,
        # ДОДАНО (2026-07-26, пряме прохання власниці — повний слід рішення
        # для price_state): саме ЦЕ значення (не сирий competitor["price"]
        # з викликаючого коду) реально пішло у формулу — decide_action()/
        # _decide_from_scan_entry() можуть занулити довіру до конкурента
        # (низький score, конфлікт розміру, competitor_alive=False) ще ДО
        # виклику цієї функції, тож будь-яке інше джерело точки candidate
        # заднім числом було б ненадійним (саме це показав живий приклад
        # SKU 292858).
        "competitor_price": min_competitor,
    }


def decide_price(
    cost: float,
    min_competitor_rozetka: float | None,
    min_competitor_prom: float | None = None,
    category_name: str | None = None,
    prom_category_id: int | None = None,
) -> dict:
    """
    Рахує рішення ОКРЕМО для кожного майданчика (Prom, Rozetka) — не лише
    різні комісії (категорійна для Prom, орієнтовний дефолт для Rozetka),
    а й ОКРЕМІ, незалежні ціни конкурента для кожного майданчика (виправлено
    2026-07-11 — раніше одна спільна ціна конкурента з Rozetka помилково
    підставлялась і в Prom-розрахунок теж, див. докстрінг файлу). Повертає
    обидва результати під ключами "prom"/"rozetka".

    prom_category_id (2026-07-17): реальна Prom-категорія товару з
    prom_category_cache.json, якщо є — застосовується лише до "prom"
    (Rozetka категорія не параметризована, див. _rozetka_tiered_commission).
    """
    return {
        "prom": decide_price_for_platform(cost, min_competitor_prom, "prom", category_name, prom_category_id),
        "rozetka": decide_price_for_platform(cost, min_competitor_rozetka, "rozetka"),
    }


# ---------------------------------------------------------------------------
# Checkpoint (лише денний ліміт/лічильники; самі результати живуть у CSV)
# ---------------------------------------------------------------------------

def load_checkpoint() -> dict:
    if CHECKPOINT_FILE.exists():
        return json.loads(CHECKPOINT_FILE.read_text(encoding="utf-8"))
    return {"last_run_date": None, "processed_today": 0}


def save_checkpoint(cp: dict) -> None:
    CHECKPOINT_FILE.write_text(json.dumps(cp, ensure_ascii=False, indent=2), encoding="utf-8")


def _bump_checkpoint_for_today() -> dict:
    cp = load_checkpoint()
    today = date.today().isoformat()
    if cp.get("last_run_date") != today:
        cp["last_run_date"] = today
        cp["processed_today"] = 0
    return cp


