#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""test_feed_title_norm.py — правила нормалізації регістру назв (SEO, 14.10.2026): R0 не чіпати латиницю/цифри/≤3 літер/одиниці; R1 слово капсом ≥4 → Перша велика; R2 кольори → нижній регістр;
R3 ≥60% великих → весь текст нижнім + цитати з великої; R4 перша велика, ≤150 без обрізання слова. Плюс інваріанти: ідемпотентність, цифри/латиниця незмінні, нормальні назви не змінюються.
`python test_feed_title_norm.py` → exit 0/1."""
import os
import sys

if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from feed_title_norm import normalize_title as n  # noqa: E402

F = []


def chk(name, got, want):
    ok = got == want
    print(f"[{'OK ' if ok else 'FAIL'}] {name}" + ("" if ok else f"\n      отримано: {got!r}\n      очікувано: {want!r}"))
    if not ok:
        F.append(name)


# приклади SEO
chk("колір у дужках капсом → нижній регістр", n("Сквіш антистрес кубик льоду 5 см кольоровий (ФІОЛЕТОВИЙ)"), "Сквіш антистрес кубик льоду 5 см кольоровий (фіолетовий)")
chk("R1: МАХІ → Махі, решта без змін", n('Пазли МАХІ "Спайдер мен" (24 ел)'), 'Пазли Махі "Спайдер мен" (24 ел)')
chk("R3 (≥60% капсу): весь текст нижнім, перша велика, одиниці малі", n("МʼЯКА ІГРАШКА ЛАБУБУ, 42 СМ").replace("лабубу", "Лабубу"), "Мʼяка іграшка Лабубу, 42 см")
chk("R3: цитата з великої, розміри незмінні", n('КОШИК ДЛЯ ІГРАШОК "ТИГРЕНЯТКО" Р-Р 38*38*44 СМ'), 'Кошик для іграшок "Тигренятко" р-р 38*38*44 см')
chk("R0: ЮДО має 3 літери → лишається (не 4), КОТИК (5) → Котик", n('Набір для ліплення "ЮДО клей" КОТИК'), 'Набір для ліплення "ЮДО клей" Котик')
# R0
chk("R0: слово з цифрою/дефісом+цифра не чіпаємо", n("Конструктор НИК-1, 87 дет"), "Конструктор НИК-1, 87 дет")
chk("R0: латиниця не чіпається", n("Набір LEGO CITY для хлопчика"), "Набір LEGO CITY для хлопчика")
chk("R0: коротке слово капсом (≤3 літер) лишаємо", n("Гра ТМ для всієї родини"), "Гра ТМ для всієї родини")
chk("R2: кілька кольорів, у т.ч. складений", n("Блокнот ЧОРНО-БІЛИЙ та РОЖЕВИЙ"), "Блокнот чорно-білий та рожевий")
chk("R2: російські кольори", n("Мяч РОЗОВЫЙ и ГОЛУБОЙ"), "Мяч розовый и голубой")
chk("R4: перша літера велика", n("конструктор будиночок"), "Конструктор будиночок")
chk("нормальна назва не змінюється", n('Конструктор "Зоопарк" (120 деталей), для дітей 3+'), 'Конструктор "Зоопарк" (120 деталей), для дітей 3+')
chk("порожня назва", n(""), "")
chk("лише латиниця/цифри не чіпаємо", n("LEGO 12345"), "LEGO 12345")
# довжина: не обрізати посеред слова
long = "Слово " * 40
out = n(long, 150)
chk("ліміт 150: не посеред слова, ≤150", len(out) <= 150 and out.endswith("Слово"), True)
# ідемпотентність і збереження цифр/латиниці на наборі
samples = ['Пазли МАХІ "Спайдер мен" (24 ел)', "МʼЯКА ІГРАШКА ЛАБУБУ, 42 СМ", "Блокнот ЧОРНО-БІЛИЙ та РОЗОВЫЙ", "Конструктор НИК-1 87 дет", 'Набір для ліплення "ЮДО клей" КОТИК']
import re
chk("ідемпотентність (повторний прогін нічого не міняє)", [n(n(s)) for s in samples], [n(s) for s in samples])
chk("цифри й латиниця збережені побуквено", all(re.findall(r"[A-Za-z0-9*+\-]+", n(s)) == re.findall(r"[A-Za-z0-9*+\-]+", s) for s in samples), True)

# власні назви в назві, що вся капсом (R3): «Майнкрафт», не «майнкрафт» (правка SEO)
chk("R3: МАЙНКРАФТ → Майнкрафт, решта нижнім", n("3D БРЕЛОКИ MINECRAFT / МАЙНКРАФТ КРІПЕР"), "3D брелоки MINECRAFT / Майнкрафт кріпер")
chk("R3: ЛАБУБУ в імені лишається з великої, СМ → см", n("МʼЯКА ІГРАШКА ЛАБУБУ, 42 СМ"), "Мʼяка іграшка Лабубу, 42 см")
chk("R3: загальні слова (КОТИК) нижнім, не плутаються з власними", n('КОШИК ДЛЯ ІГРАШОК "КОТИК" Р-Р 38*38*44 СМ'), 'Кошик для іграшок "Котик" р-р 38*38*44 см')
chk("не-R3: МАЙНКРАФТ у звичайній назві → Майнкрафт (R1)", n("Набір для ліплення МАЙНКРАФТ 12 кольорів"), "Набір для ліплення Майнкрафт 12 кольорів")
chk("ідемпотентність і для власних назв", n(n("3D БРЕЛОКИ MINECRAFT / МАЙНКРАФТ КРІПЕР")), n("3D БРЕЛОКИ MINECRAFT / МАЙНКРАФТ КРІПЕР"))

# знахідки аудиту #758
chk("R3: скорочення БТР/ТМ/ПВХ не псуємо (R0), службові слова ПО/З нижнім", n("ТАНК БТР-80 НА РАДІОКЕРУВАННІ ПВХ ПО 3 ТМ"), "Танк БТР-80 на радіокеруванні ПВХ по 3 ТМ")
chk("R3: латинські слова в лапках НЕ піднімаємо (Big slime лишається)", n('СЛАЙМ "Big slime" ДЛЯ ДІТЕЙ ВЕЛИКИЙ НАБІР'), 'Слайм "Big slime" для дітей великий набір')
chk("назва з цифри лишається як є (3d, 6 кубиків)", (n("3d брелок Анубіс"), n("6 кубиків для гри")), ("3d брелок Анубіс", "6 кубиків для гри"))
chk("іменники, схожі на кольори (БІЛОЧКА, БІЛКА, СІРНИК, ЗОЛОТО) → Title, а не нижній регістр", n("Мʼяка плюшева іграшка для дітей БІЛОЧКА і БІЛКА, СІРНИК, ЗОЛОТО"), "Мʼяка плюшева іграшка для дітей Білочка і Білка, Сірник, Золото")
chk("справжні кольори й форми (БІЛИЙ, БІЛА, ЗОЛОТИЙ, ГОЛУБОЙ, СИНІЙ) нижнім", n("Мяч БІЛИЙ БІЛА ЗОЛОТИЙ ГОЛУБОЙ СИНІЙ"), "Мяч білий біла золотий голубой синій")
chk("апостроф U+02BC: МʼЯКА/ДЕРЕВʼЯНА/МʼЯТНИЙ нормалізуються (36 назв у корпусі)", n("Іграшка для малят ДЕРЕВʼЯНА з мʼятним відтінком (МʼЯТНИЙ)"), "Іграшка для малят Деревʼяна з мʼятним відтінком (мʼятний)")
chk("ru: російські власні назви в R3 (УКРАИНА, ЛЕГО, МИККИ) з великої", n("ИГРУШКА УКРАИНА НАБОР ЛЕГО И МИККИ"), "Игрушка Украина набор Лего и Микки")

print("\nFAIL:" if F else "\nOK: усі перевірки пройдені", *F, sep="\n")
sys.exit(1 if F else 0)
