#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
test_vchasno_akty_kandydaty.py — регрес-тест виявлення актів Вчасно (vchasno_akty_kandydaty.py,
замовлення незалежного аудитора бухгалтерії, КОДВ_журнал «ДОПОВНЕННЯ 6», 2026-09-17/18: два
реальні хвости (подвійний облік 734,36, пропущений акт 178,97) висіли місяць, бо номер акта
↔ згадка в книзі звірялась ЛИШЕ вручну).

Мережа НЕ потрібна: тестує парсинг імені файлу (реальні назви, звірені живо) і текстовий
пошук у книзі (реальний наратив, звірений живо). `python test_vchasno_akty_kandydaty.py` →
exit 0/1.
"""
import sys

if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")

import vchasno_akty_kandydaty as va

_FAILS = []


def _chk(name, cond):
    print(f"[{'OK ' if cond else 'FAIL'}] {name}")
    if not cond:
        _FAILS.append(name)


# 1: parse_akt_filename — на РЕАЛЬНИХ назвах файлів (звірено живо 2026-09-18, документи_КОДВ)
_cases = [
    ("2026-08-31_rozetka_akt_royalti_TA00482473_178.97.pdf",
     {"vendor": "rozetka", "doc_id": "TA00482473", "amount": 178.97, "date": "2026-08-31"}),
    ("2026-08-31_rozetka_akt_dostup_TA00482472_324.36.pdf",
     {"vendor": "rozetka", "doc_id": "TA00482472", "amount": 324.36, "date": "2026-08-31"}),
    ("2026-07-31_prom_akt_UA-00011321442_817.47.pdf",
     {"vendor": "prom", "doc_id": "UA-00011321442", "amount": 817.47, "date": "2026-07-31"}),
    ("2026-07-31_prom_akt_UA-00011321442_817.47_ne_nova_vytrata.pdf",
     {"vendor": "prom", "doc_id": "UA-00011321442", "amount": 817.47, "date": "2026-07-31"}),
    ("2026-08-31_allo_akt_AL000389851_120.00.pdf",
     {"vendor": "allo", "doc_id": "AL000389851", "amount": 120.00, "date": "2026-08-31"}),
    ("2026-07-31_rozetkapay_akt_000573566.pdf",
     {"vendor": "rozetkapay", "doc_id": "000573566", "amount": None, "date": "2026-07-31"}),
    ("2026-09-16_eva_akt_RU000154242.pdf",
     {"vendor": "eva", "doc_id": "RU000154242", "amount": None, "date": "2026-09-16"}),
    ("2026-08-13_np_akt_NP-018826846_130.00.xml.json",
     {"vendor": "np", "doc_id": "NP-018826846", "amount": 130.00, "date": "2026-08-13"}),
    # HostIQ формує номери документів із 1-літерним суфіксом ("1375492H") — знайдено живо
    # 2026-09-19 (vchasno_cabinet_scraper.py), _ID_RE фіксовано під це.
    ("2026-09-04_hostiq_akt_1375492H_1013.84.pdf",
     {"vendor": "hostiq", "doc_id": "1375492H", "amount": 1013.84, "date": "2026-09-04"}),
]
for filename, expected in _cases:
    got = va.parse_akt_filename(filename)
    _chk(f"parse_akt_filename({filename[:45]}...): {expected['doc_id']}", got == expected)

_chk("parse_akt_filename: без розпізнаного номера → None (не падає, не вигадує)",
     va.parse_akt_filename("2026-07-31_novapay_akt_kompensatsii_1175.00_komisia_5.89.pdf") is None)
_chk("parse_akt_filename: файл поза конвенцією → None",
     va.parse_akt_filename("readme.txt") is None)

# 1b: РЕГРЕС — аудит PR #571 знайшов живо: "zvirky" (акти звірки НП) містять у назві файлу
# НОМЕР ДОГОВОРУ (1081695), не унікальний номер документа. Якби взяти його за doc_id: (а)
# два акти звірки за РІЗНІ періоди дедуп злив би в один кандидат (обидва дають однаковий
# doc_id, різняться лише датами в хвості); (б) exact-match видав би ХИБНЕ "✅ у книзі" для
# ОБОХ, бо номер договору й так зустрічається в наративі НЕ пов'язаних з цим актом рядків
# книги (окремі рахунки НП того самого договору). Money-critical напрямок: хибний ✅ ховає
# реальну прогалину. Тому "zvirky"-файли МУСЯТЬ повертати None (unparsed), не doc_id.
_chk("parse_akt_filename: 'zvirky' (номер ДОГОВОРУ, не документа) → None, не хибний doc_id",
     va.parse_akt_filename("2026-08-11_np_akt_zvirky_1081695_12.05-11.08.xlsx") is None)
_chk("parse_akt_filename: другий 'zvirky' той самий договір, інший період → теж None (не той самий doc_id)",
     va.parse_akt_filename("2026-08-17_np_akt_zvirky_1081695_18.05-17.08.xlsx") is None)

# 2: _already_in_book — РЕГРЕС на реальних багах, знайдених живими прогонами 2026-09-18/23.
# НОВИЙ формат (2026-09-23, фікс бага (8) черги 2): _already_in_book приймає СПИСОК клітинок
# книги (не конкатенований рядок) — офсет "власного" номера рахується В МЕЖАХ КЛІТИНКИ.
# 2a: Нова Пошта — файл латиницею "NP-...", книга кирилицею "№НП-..." (рядок 35)
_BOOK_NP = "Нова Пошта, рахунок №НП-018826846 від 10.08.2026."
_chk("_already_in_book: НП кирилиця в книзі проти латиниці у doc_id — числове ядро рятує",
     va._already_in_book("NP-018826846", [_BOOK_NP]))

# 2b: ALLO — файл з префіксом+нулями "AL000389851", книга без них "№389851" (рядок 81)
_BOOK_ALLO = "ALLO, Акт надання послуг №389851 від 31.08.2026"
_chk("_already_in_book: ALLO без префікса/нулів у книзі — числове ядро рятує",
     va._already_in_book("AL000389851", [_BOOK_ALLO]))

# 2c: точний збіг (Rozetka/Prom — бухгалтер копіює номер дослівно)
_BOOK_TA = "Термінал доступу Rozetka, акт TA00482473, 178.97 грн"
_chk("_already_in_book: точний збіг (Rozetka)", va._already_in_book("TA00482473", [_BOOK_TA]))

# 2d: справді відсутній — не знаходить (RozetkaPay-подібний, свідомо не внесений)
_chk("_already_in_book: справді відсутній — не знаходить",
     not va._already_in_book("000573566", [_BOOK_NP, _BOOK_ALLO, _BOOK_TA]))

# 2e: захист від коротких випадкових чисел — числове ядро <5 цифр НЕ використовується
_chk("_already_in_book: коротке числове ядро (<5 цифр) не дає хибних збігів",
     not va._already_in_book("AL1234", ["щось із 1234 всередині іншого числа 51234"]))

# 2f: doc_id без цифр узагалі (гіпотетично) — не падає
_chk("_already_in_book: doc_id без цифр наприкінці — не падає",
     va._already_in_book("ABCDEF", ["текст без doc_id"]) is False)

# ── 2g: ЖИВИЙ РЕЦИДИВ (2026-09-23, баг (8) черги 2) — рядок 82 книги (дослівний фрагмент,
#      звірено живо) ЗГАДУЄ TA00482473 у поясненні до ІНШОГО акту (TA00482472), не як
#      власний номер рядка. Раніше (конкатенований підрядковий пошук) це давало ХИБНЕ
#      "✅ у книзі" — акт TA00482473 (справжній, свій рядок книги 119) 4+ доби виглядав
#      уже внесеним, хоча рядка не мав. ──
_ROW82 = ("Термінал Розетка, Акт надання послуг №TA00482472 від 31.08.2026 — платформний "
          "доступ: організація видачі відправлень (спецумови) 51.00 + безумовна щомісячна "
          "плата за доступ до rozetka.com.ua 100.00 + доступ у зв'язку з обсягом продажу "
          "119.30, Всього з ПДВ 324.36. ⚠️ ОКРЕМА стаття від роялті за ТМ (акт "
          "№TA00482473, 178.97, за той самий місяць) — не дублює, платформний доступ і "
          "роялті різні акти того самого контрагента.")
_chk("живий рецидив: TA00482472 (власний номер рядка 82, офсет ~38) — знайдено",
     va._already_in_book("TA00482472", [_ROW82]))
_chk("живий рецидив: TA00482473 (лише ЗГАДКА в поясненні рядка 82, офсет ~304) — "
     "НЕ вважається 'у книзі' (фікс бага 8, раніше тут була хибна ✅)",
     not va._already_in_book("TA00482473", [_ROW82]))

# ── 2h: той самий акт, коли він ДІЙСНО має власний рядок (119) — знаходиться ──
_ROW119 = ("Термінал Розетка, Акт надання послуг №TA00482473 від 31.08.2026 — роялті за "
           "користування торгової марки Rozetka, 178.97 грн без ПДВ.")
_chk("живий рецидив: TA00482473 ЗІ своїм рядком (119) — знаходиться, як і має",
     va._already_in_book("TA00482473", [_ROW82, _ROW119]))

# ── 2i: другий живий приклад того самого класу — рядок 80 книги: власний номер 11865348
#      на початку, згадка "акту №11321442" (свідомо НЕ внесеного) глибоко в поясненні ──
_ROW80 = ("Prom.ua (Уапром), Акт надання послуг №11865348 від 31.08.2026 за серпень: доступ "
          "ProSale 241.43 + компенсація перевезень Новою Поштою 29.17 + пакет «Prom мікс "
          "6000» (01.08-31.08) 611.97, Всього з ПДВ 1059.09. Джерело: акт підписано у "
          "Вчасно 2026-09-14/15. ⚠️ i9 ВИПРАВЛЕНО 2026-09-18 (незалежний аудит, доповнення "
          "6, ПОДВІЙНИЙ ОБЛІК): акт №11865348 посилається на «Розр. док.: Рахунок на "
          "оплату покупцю №12128253-66 від 04.07.2026» — це ТОЙ САМИЙ рахунок, що вже "
          "повністю визнаний витратою в рядку 7. Пакет «Prom мікс 6000» 611.97 з цього "
          "акту — розподіл ТІЄЇ Ж передоплати, не нова стаття (той самий принцип, "
          "застосований до липневого акту №11321442, свідомо НЕ внесеного).")
_chk("живий приклад 2: 11865348 (власний номер рядка 80) — знайдено",
     va._already_in_book("11865348", [_ROW80]))
_chk("живий приклад 2: 11321442 (згадка 'свідомо НЕ внесеного' акту в поясненні рядка 80) "
     "— НЕ вважається 'у книзі'", not va._already_in_book("11321442", [_ROW80]))

# ── 2j: межа вікна — рівно на межі _DECLARATION_WINDOW (100 симв.) і трохи за нею ──
_chk("межа вікна: doc_id рівно на позиції window-1 (усередині) — знаходиться",
     va._already_in_book("XYZ99999", ["a" * (va._DECLARATION_WINDOW - 8) + "XYZ99999" + "b" * 50]))
_chk("межа вікна: doc_id одразу ЗА межею window — НЕ знаходиться (ні точний збіг, ні "
     "числове ядро — обидва поза window[:100], сама підрядкова частина туди не влазить)",
     not va._already_in_book("XYZ99999", ["a" * (va._DECLARATION_WINDOW + 20) + "XYZ99999"]))


if _FAILS:
    print(f"\n❌ ПРОВАЛЕНО: {len(_FAILS)} — {_FAILS}")
    sys.exit(1)
print("\n✅ Акти Вчасно: парсинг реальних імен файлів, звірка з книгою (точний збіг + "
      "числове ядро для НП/ALLO) — усе коректно")
sys.exit(0)
