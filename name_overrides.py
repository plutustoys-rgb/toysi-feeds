def apply_name_override(sku, name: str, ukr_spelling: bool = True) -> str:
    """Повертає куровану укр. назву для sku, якщо вона є; інакше — name без змін.

    Застосовується ЛИШЕ коли ukr_spelling=True (укр. відображувана назва, lang != 'rus'):
    таблиця містить укр. виправлення, у російському полі Prom <name> вони недоречні.
    Друкує WARN у stderr, якщо жива name розійшлася з очікуваною поточною (таблиця застаріла),
    але override все одно застосовує (список SEO авторитетний). Ідемпотентна, без побічних ефектів.
    """
    if not ukr_spelling or not sku:
        return name
    entry = _OVERRIDES.get(str(sku))
    if not entry:
        return name
    correct, expected_current = entry
    if expected_current and name and name != expected_current and name != correct:
        print(f"[name_override] WARN sku={sku}: жива назва «{name}» ≠ очікуваної «{expected_current}» — "
              f"куровану таблицю (name_overrides.py) час оновити; застосовую «{correct}»", file=sys.stderr)
    return correct
