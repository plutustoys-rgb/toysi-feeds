FORBIDDEN_TOYSI_CATEGORIES = frozenset({
    "мечі, ножі та шаблі",
})


def is_forbidden(item) -> bool:
    """True, якщо позиція належить до забороненої на вітрині Toysi-категорії. Приймає dict товару (`category_name`)."""
    if not isinstance(item, dict):
        return False
    return (item.get("category_name") or "").strip().lower() in FORBIDDEN_TOYSI_CATEGORIES
