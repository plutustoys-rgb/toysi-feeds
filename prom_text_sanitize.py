# -*- coding: utf-8 -*-
"""prom_text_sanitize.py — прибирає слово «зброя»/«оружие» з текстів Prom-фіду (name, description, keywords, параметри).

ЧОМУ (незалежний Аудитор кабінетів, ЗАВДАННЯ_КОДУ_з_аудиту_2026-10-03.md п.3): правило Prom [П2 п.4.2.25] дозволяє позиції лише «за умови
відсутності терміну «зброя» у назві, описі та ключових словах»; порушення = автовидалення за стоп-словом [П8]. У prom_feed_top.xml було 24–30 офер
з цим словом (напр. «Водна зброя», «Іграшкова зброя Бластер», «Категорія: Водна зброя» в описі). Площадки Rozetka/EVA/ALLO мають легальні
категорії «Водна зброя»/«Іграшкова зброя» — для них НЕ застосовується; лише Prom-фід.

Правила (з узгодженням відмінків; регістр першої літери зберігається):
  UA: ланцюжок прикметників (іграшкова/дитяча/пневматична) + зброя → «іграшка/іграшки/іграшку/іграшкою» (прикметники скидаємо: «Іграшкова дитяча зброя
      "Арбалет"» → «Іграшка "Арбалет"»); водна/водяна зброя → «водні іграшки / водних іграшок / водними іграшками»;
      голе: зброя→іграшка, зброю→іграшку, зброєю→іграшкою («зі» → «з»), зброї→іграшок («набір зброї» → «набір іграшок»), зброях/зброям/зброі.
  RU: оружие/оружия/оружию/оружием/оружии → игрушка/игрушки/игрушке/игрушкой/игрушке; водное оружие → водные игрушки; игрушечное/детское + оружие → игрушка;
      інші прикметники (огнестрельное/пневматического/увлекательное) узгоджуються до жіночого роду (-ое→-ая, -ого→-ой, -ым→-ой).
НЕ чіпає омоніми/складні слова («зброяр», «суперзброю» тощо) — невідомо, чи Prom шукає стоп-слово за підрядком; це відкрите питання до Аудитора.
Порожніх «ключових слів» не лишає: для keywords дублі після заміни видаляються (`dedupe_keywords`).
"""
import re

_FLAGS = re.IGNORECASE | re.UNICODE
_QUICK = re.compile(r"зброя|зброї|зброю|зброєю|зброях|зброям|зброі|оруж", _FLAGS)


def _case(src: str, repl: str) -> str:
    return repl[:1].upper() + repl[1:] if src[:1].isupper() else repl


# ── UA ──────────────────────────────────────────────────────────────────────────────────────────────────────
_UA_NOUN = r"(зброя|зброї|зброю|зброєю|зброях|зброям|зброі)"
_UA_ADJ = r"(?:іграшков|дитяч|водн|водян|пневматичн)(?:а|у|ої|ій|ою|і|е|ого|их|ими)"
_UA_NOUN_MAP = {"зброя": "іграшка", "зброю": "іграшку", "зброєю": "іграшкою", "зброї": "іграшки", "зброях": "іграшках",
                "зброям": "іграшкам", "зброі": "іграшки"}
_UA_WATER = {"зброя": "водні іграшки", "зброю": "водні іграшки", "зброєю": "водними іграшками", "зброї": "водних іграшок",
             "зброях": "водних іграшках", "зброям": "водним іграшкам", "зброі": "водних іграшок"}
# голе слово: родовий («набір зброї») — множина «іграшок»
_UA_BARE = {**_UA_NOUN_MAP, "зброї": "іграшок", "зброі": "іграшок"}

_UA_CHAIN = re.compile(r"\b((?:" + _UA_ADJ + r"\s+){1,3})" + _UA_NOUN + r"\b", _FLAGS)
_UA_BARE_RE = re.compile(r"\b" + _UA_NOUN + r"\b", _FLAGS)


def _ua_chain(m):
    chain, noun = m.group(1).lower(), m.group(2)
    water = bool(re.search(r"\b(водн|водян)", chain))
    table = _UA_WATER if water else _UA_NOUN_MAP
    return _case(m.group(0), table[noun.lower()])


def _ua_bare(m):
    return _case(m.group(0), _UA_BARE[m.group(1).lower()])


# ── RU ──────────────────────────────────────────────────────────────────────────────────────────────────────
_RU_NOUN = r"(оружие|оружия|оружию|оружием|оружии)"
_RU_NOUN_MAP = {"оружие": "игрушка", "оружия": "игрушки", "оружию": "игрушке", "оружием": "игрушкой", "оружии": "игрушке"}
_RU_WATER = {"оружие": "водные игрушки", "оружия": "водных игрушек", "оружию": "водным игрушкам", "оружием": "водными игрушками",
             "оружии": "водных игрушках"}
_RU_ADJ_END = {"ое": "ая", "ого": "ой", "ому": "ой", "ым": "ой", "ом": "ой"}
# Прикметники — ЛИШЕ з білого списку основ (аудит #627: «[а-яё]+ом» калічила «набором/много/размером оружия» → «наборой игрушки»)
_RU_ADJ_STEMS = r"(?:игрушечн|детск|водн|огнестрельн|пневматическ|культов|увлекательн|реальн|настоящ|боев|военн|пластиков|металлическ)"
_RU_ADJ_RE = re.compile(r"\b(?P<chain>(?:" + _RU_ADJ_STEMS + r"[а-яё]*?(?:ое|ого|ому|ым|ом)\s+){1,3})" + _RU_NOUN + r"\b", _FLAGS)
# голе «оружия» (род. відм. після «набор/комплект/много/размер…») → множина «игрушек»; решта форм — як у _RU_NOUN_MAP
_RU_BARE_MAP = {**_RU_NOUN_MAP, "оружия": "игрушек"}


def _ru_adj(m):
    """Ланцюжок прикметників перед «оружие»: водн* → «водные игрушки…»; игрушечн*/детск* → лише іменник; решта — узгодження до жіночого роду."""
    adjs, noun = m.group("chain").split(), m.group(m.lastindex).lower()
    low = [a.lower() for a in adjs]
    if any(a.startswith("водн") for a in low):
        return _case(m.group(0), _RU_WATER[noun])
    kept = [a for a in adjs if not a.lower().startswith(("игрушечн", "детск"))]
    out = []
    for a in kept:
        for end, fem in _RU_ADJ_END.items():
            if a.lower().endswith(end):
                a = a[:len(a) - len(end)] + (fem if a[-1].islower() else fem.upper())
                break
        out.append(a)
    res = " ".join(out + [_RU_NOUN_MAP[noun]])
    return _case(m.group(0), res)


_RU_BARE_RE = re.compile(r"\b" + _RU_NOUN + r"\b", _FLAGS)


def sanitize(text):
    """Повертає текст без «зброя/оружие» (None/порожнє — як є)."""
    if not text or not _QUICK.search(text):
        return text
    out = _UA_CHAIN.sub(_ua_chain, text)
    out = _UA_BARE_RE.sub(_ua_bare, out)
    out = re.sub(r"\b([Зз])і(\s+іграшк)", r"\1\2", out)       # «зі іграшкою» → «з іграшкою»
    out = _RU_ADJ_RE.sub(_ru_adj, out)
    out = _RU_BARE_RE.sub(lambda m: _case(m.group(0), _RU_BARE_MAP[m.group(1).lower()]), out)
    return out


def dedupe_keywords(csv: str) -> str:
    """Після заміни ключові слова можуть задублюватись («іграшка, іграшка») — лишаємо перші входження (регістр ігнорується)."""
    if not csv:
        return csv
    seen, res = set(), []
    for part in csv.split(","):
        p = part.strip()
        k = p.lower()
        if p and k not in seen:
            seen.add(k)
            res.append(p)
    return ", ".join(res)


def has_weapon_word(text) -> bool:
    return bool(text) and bool(re.search(r"\bзброя\b|\bзброї\b|\bзброю\b|\bзброєю\b|\bзброях\b|\bзброям\b|\bзброі\b|\bоружи(?:е|я|ю|ем|и)\b", text, _FLAGS))
