# -*- coding: utf-8 -*-
"""prom_text_sanitize.py — прибирає слово «зброя»/«оружие» з текстів Prom-фіду (name, description, keywords, параметри).

ЧОМУ (незалежний Аудитор кабінетів, ЗАВДАННЯ_КОДУ_з_аудиту_2026-10-03.md п.3): правило Prom [П2 п.4.2.25] дозволяє позиції лише «за умови
відсутності терміну «зброя» у назві, описі та ключових словах»; порушення = автовидалення за стоп-словом [П8]. У prom_feed_top.xml було 24 офери
з цим словом (напр. «Водна зброя», «Іграшкова зброя Бластер», «Категорія: Водна зброя» в описі). Площадки Rozetka/EVA/ALLO мають легальні
категорії «Водна зброя»/«Іграшкова зброя» — для них НЕ застосовується; лише Prom-фід.

Правила (від довших фраз до голого слова; регістр першої літери зберігається):
  «водна/водяна зброя» → «водні іграшки» · «іграшкова/дитяча/іграшкове …» + зброя → «іграшка» · голе «зброя/зброї/зброю/зброєю» → «іграшка/…» ·
  рос.: «водное оружие» → «водные игрушки», «игрушечное оружие» → «игрушка», голе «оружие» → «игрушка».
Порожніх «ключових слів» не лишає: для keywords дублі після заміни видаляються (`dedupe_keywords`).
"""
import re

_CYR = "A-Za-zА-Яа-яІіЇїЄєҐґЁё"


def _case(src: str, repl: str) -> str:
    return repl[:1].upper() + repl[1:] if src[:1].isupper() else repl


# (патерн, заміна) — порядок важливий: спершу довші фрази.
_RULES = [
    (r"\b(водн[аоуі]я?|водян[аоуі]я?)\s+зброя\b", "водні іграшки"),
    (r"\b(водн[аоуі]я?|водян[аоуі]я?)\s+зброї\b", "водних іграшок"),
    (r"\b(іграшков[аоуі]|дитяч[аоуі])\s+зброя\b", None),          # → «іграшка»/«дитяча іграшка» (див. _sub_toy)
    (r"\b(іграшков[аоуі]|дитяч[аоуі])\s+зброї\b", None),
    (r"\b(іграшков[аоуі]|дитяч[аоуі])\s+зброю\b", None),
    (r"\bводн(ое|ого|ому|ым)\s+оружи(е|я|ю|ем)\b", "водные игрушки"),
    (r"\b(игрушечн\w+|детск\w+)\s+оружи(е|я|ю|ем)\b", "игрушка"),
    (r"\bзброя\b", "іграшка"), (r"\bзброї\b", "іграшки"), (r"\bзброю\b", "іграшку"), (r"\bзброєю\b", "іграшкою"),
    (r"\bоружи(е|я|ю|ем)\b", "игрушка"),
]
_FLAGS = re.IGNORECASE | re.UNICODE


def sanitize(text):
    """Повертає текст без «зброя/оружие» (None/порожнє — як є)."""
    if not text or not re.search(r"зброя|зброї|зброю|зброєю|оруж", text, _FLAGS):
        return text
    out = text
    for pat, repl in _RULES:
        if repl is None:
            out = re.sub(pat, lambda m: _case(m.group(0), "іграшка" if m.group(1).lower().startswith("іграшков") else "дитяча іграшка")
                         if m.group(0).lower().endswith("зброя") else
                         _case(m.group(0), "іграшки" if m.group(0).lower().endswith("зброї") else "іграшку"), out, flags=_FLAGS)
        else:
            out = re.sub(pat, lambda m, r=repl: _case(m.group(0), r), out, flags=_FLAGS)
    return out


def dedupe_keywords(csv: str) -> str:
    """Після заміни ключові слова можуть задублюватись («іграшка, іграшка») — лишаємо перші входження (регістр ігнорується)."""
    if not csv:
        return csv
    seen, res = set(), []
    for part in csv.split(","):
        p = part.strip()
        k = p.lower()
        if p and k not in seen:
            seen.add(k)
            res.append(p)
    return ", ".join(res)


def has_weapon_word(text) -> bool:
    return bool(text) and bool(re.search(r"зброя|зброї|зброю|зброєю|оружи", text, _FLAGS))
