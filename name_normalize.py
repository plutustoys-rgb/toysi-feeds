"""name_normalize.py — механічна чистка назв товарів для фідів (запит SEO 2026-08-23).

ПРОБЛЕМА: у назвах з Toysi латинські літери маскуються під кирилицю (гомогліфи) —
`Koнcтpуктop`, `Пocудa`, `Вантажiвка`. Такий товар НЕВИДИМИЙ у пошуку («конструктор» не
знаходить «Koнcтpуктop»). Плюс рос. «антистресс», подвійні пробіли, латинська `m` у «см».

ПРАВИЛО SEO (звірено ним на живих фідах, звужує 157→40 без жодного бренду): у ТОКЕНІ
замінюємо латинські гомогліфи на кирилицю ЛИШЕ якщо (1) у токені ≥2 кириличні літери І
(2) ВСІ латинські символи токена — гомогліфи. Якщо є хоч одна НЕ-гомогліфна латинська
(b d f g j k l n q r s u v w z …) — це справжнє латинське слово (USB-кабель, LAND ROVER,
Tiki Wiki, My Color Case) → НЕ чіпаємо. Це НЕ переклад — суто заміна символів, ризик нульовий.
"""
import re

# Латинський гомогліф → кирилична літера (перелік гомогліфів — від SEO).
_HOMOGLYPH = {
    "a": "а", "c": "с", "e": "е", "i": "і", "o": "о", "p": "р", "x": "х", "y": "у",
    "A": "А", "B": "В", "C": "С", "E": "Е", "H": "Н", "I": "І", "K": "К", "M": "М",
    "O": "О", "P": "Р", "T": "Т", "X": "Х", "Y": "У",
}
_LATIN = re.compile(r"[A-Za-z]")
_CYR = re.compile(r"[А-Яа-яЁёЇїІіЄєҐґ]")
# «Токен» = МАКСИМАЛЬНА руна літер (кир+лат). Розбиваємо саме так, а НЕ по пробілах: інакше
# «мого.CITY» (крапка без пробілу) склеюється в один токен і бренд CITY хибно підмінюється
# (жива знахідка 2026-08-23 на rozetka_feed). Пунктуація/цифри/пробіли розділяють руни.
_LETTER_RUN = re.compile(r"[A-Za-zА-Яа-яЁёЇїІіЄєҐґ]+")
_ANTISTRESS = re.compile(r"антистре[сcс]{2,}", re.IGNORECASE)  # рос. «антистресс» (латинська/подвійна с)


def _fix_token(tok: str) -> str:
    """Одна руна літер. Замінює гомогліфи за правилом SEO."""
    latin = _LATIN.findall(tok)
    if not latin:
        return tok
    # ≥2 кириличні І ВСІ латинські — гомогліфи → підміна; інакше лишаємо (справжнє лат. слово).
    if len(_CYR.findall(tok)) >= 2 and all(ch in _HOMOGLYPH for ch in latin):
        return "".join(_HOMOGLYPH.get(ch, ch) for ch in tok)
    return tok


def normalize_display_name(name: str | None, ukr_spelling: bool = False) -> str | None:
    """Механічна чистка назви. Повертає None/порожнє як є. Ідемпотентна.

    УНІВЕРСАЛЬНЕ (завжди, безпечно в будь-якій мові): гомогліфна підміна латиниці за правилом
    SEO + схлопування подвійних пробілів + латинська `m` у вимірі «см».
    УКРАЇНСЬКО-МОВНЕ (лише `ukr_spelling=True` — для укр. полів name_ua/Rozetka-name): `антистресс`
    → `антистрес` (рос. подвійне «с»). НЕ застосовувати до РОСІЙСЬКОГО поля `name` Prom — там
    `антистресс` правильний, інакше калічимо коректну рос. назву (жива знахідка 2026-08-23)."""
    if not name:
        return name
    s = _ANTISTRESS.sub("антистрес", name) if ukr_spelling else name
    # латинська 'm' у вимірі «см» (універсально — «см» однаково в укр/рос): після кир. 'с' на межі слова.
    s = re.sub(r"(?<=с)m\b", "м", s)
    s = _LETTER_RUN.sub(lambda m: _fix_token(m.group()), s)  # по рунах літер, не по пробілах
    s = re.sub(r"[ \t]{2,}", " ", s).strip()
    return s
