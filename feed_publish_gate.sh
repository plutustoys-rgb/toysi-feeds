#!/bin/bash
# feed_publish_gate.sh — гейт розміру фіду ПЕРЕД публікацією (source-ується з publish_feed_pipeline_vps.sh; окремо тестується test_feed_publish_gate.py).
#
# НАВІЩО (12.10.2026, Консультант + власник): публікація робила `cp` без перевірки розміру. Порожній чи обрізаний прогін (збій Toysi/мережі) перезаписував
# робочий фід; для Prom це катастрофа: налаштування імпорту «Статус товарів, яких немає в файлі» = «Видалені» ВИДАЛЯЄ з кабінету все, чого нема у файлі.
# Гейт не пускає у публікацію фід, який: (а) менший за абсолютний мінімум, АБО (б) втратив понад 30% позицій проти ВЖЕ опублікованого.
# Заблокований фід НЕ копіюється: лишається попередня опублікована версія (її вже підтягнув `git checkout origin/feed-data -- .`).
# Свідоме масове скорочення: FEED_GATE_OVERRIDE=1 у середовищі прогону (одноразово, робить власник/Код з причиною в журналі).

# кількість позицій у фіді: <item> (Google/Meta/Bing, RSS) або <offer (EVA/ALLO/Prom, YML). Порожній/відсутній файл → 0.
feed_offer_count() {
    [ -s "$1" ] || { echo 0; return; }
    grep -o -E '<item>|<offer[ >]' "$1" | wc -l | tr -d ' '
}

# feed_gate_ok <новий> <опублікований-раніше> <абсолютний-мінімум>; 0 = можна публікувати, 1 = заблоковано (причина в stdout)
feed_gate_ok() {
    local new="$1" old="$2" min_abs="${3:-1}" n o
    n=$(feed_offer_count "$new")
    o=$(feed_offer_count "$old")
    if [ "${FEED_GATE_OVERRIDE:-0}" = "1" ]; then
        echo "override: ${n} позицій (було ${o})"
        return 0
    fi
    if [ "$n" -lt "$min_abs" ]; then
        echo "позицій ${n} < мінімум ${min_abs} (було опубліковано ${o})"
        return 1
    fi
    if [ "$o" -gt 0 ] && [ $((n * 100)) -lt $((o * 70)) ]; then
        echo "позицій ${n} проти ${o} опублікованих: просідання понад 30%"
        return 1
    fi
    echo "ok: ${n} позицій (було ${o})"
    return 0
}
